import AppKit

/// Fundamentals and range statistics derived from the simulated history.
final class KeyStatsPanel: PanelViewController {
    private var values: [String: NSTextField] = [:]
    private let summary = NSTextField.label(font: Theme.font(12.5), color: Theme.textSecondary)

    private static let keys = [
        ["Market Cap", "Shares Out", "EPS (TTM)", "P/E (TTM)"],
        ["52W High", "52W Low", "Avg Volume (30D)", "Volatility"],
        ["Sector", "Exchange", "Type", "Beta (est.)"],
    ]

    init(env: AppEnvironment, tabTitle: String = "Key Stats") {
        super.init(env: env, title: tabTitle)
    }

    override func buildContent() {
        let grid = NSGridView(views: Self.keys.map { row in
            row.flatMap { key -> [NSView] in
                let value = NSTextField.label("--", font: Theme.numberFont(13, .medium))
                values[key] = value
                return [NSTextField.label(key, font: Theme.font(11.5), color: Theme.textSecondary), value]
            }
        })
        grid.rowSpacing = 14
        grid.columnSpacing = 14
        for index in stride(from: 1, to: grid.numberOfColumns, by: 2) {
            grid.column(at: index).width = 110
        }
        summary.maximumNumberOfLines = 0
        summary.lineBreakMode = .byWordWrapping

        view.addSubviews(grid, summary)
        NSLayoutConstraint.activate([
            grid.topAnchor.constraint(equalTo: view.topAnchor, constant: 18),
            grid.leadingAnchor.constraint(equalTo: view.leadingAnchor, constant: 18),
            grid.trailingAnchor.constraint(lessThanOrEqualTo: view.trailingAnchor, constant: -18),
            summary.topAnchor.constraint(equalTo: grid.bottomAnchor, constant: 22),
            summary.leadingAnchor.constraint(equalTo: view.leadingAnchor, constant: 18),
            summary.trailingAnchor.constraint(lessThanOrEqualTo: view.trailingAnchor, constant: -18),
        ])
    }

    override func marketDidTick() {}

    override func refresh() {
        guard let instrument = env.market.instrument(linkedSymbol), let quote = env.market.quote(for: linkedSymbol) else { return }
        let year = env.market.candles(for: linkedSymbol, interval: .day).suffix(252)
        let month = year.suffix(30)
        let isStock = instrument.kind == .stock
        let set: (String, String) -> Void = { [values] key, text in values[key]?.stringValue = text }

        set("Market Cap", isStock ? Format.compact(instrument.sharesOutstanding * quote.last) : "--")
        set("Shares Out", isStock ? Format.compact(instrument.sharesOutstanding) : "--")
        set("EPS (TTM)", isStock ? Format.price(instrument.earningsPerShare) : "--")
        set("P/E (TTM)", isStock && instrument.earningsPerShare > 0 ? String(format: "%.2f", quote.last / instrument.earningsPerShare) : "--")
        set("52W High", year.map(\.high).max().map(Format.price) ?? "--")
        set("52W Low", year.map(\.low).min().map(Format.price) ?? "--")
        set("Avg Volume (30D)", instrument.isTradable && !month.isEmpty ? Format.compact(month.map(\.volume).reduce(0, +) / Double(month.count)) : "--")
        set("Volatility", String(format: "%.1f%%", instrument.volatility * 100))
        set("Sector", instrument.sector)
        set("Exchange", instrument.exchange)
        set("Type", instrument.kind.rawValue)
        set("Beta (est.)", String(format: "%.2f", instrument.volatility / 0.16))

        summary.stringValue = "\(instrument.name) (\(instrument.symbol)) is listed on \(instrument.exchange) in the \(instrument.sector) group. "
            + "All figures in OpenWebull are generated by the built-in market simulator and are not real market data."
    }
}
